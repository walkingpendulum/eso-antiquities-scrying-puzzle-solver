import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { relative, join } from "node:path";
async function files(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) =>
      entry.isDirectory()
        ? files(join(dir, entry.name))
        : join(dir, entry.name),
    ),
  );
  return nested.flat();
}
const paths = (await files("dist"))
  .filter((path) => !path.endsWith("/sw.js"))
  .sort();
const hash = createHash("sha256");
for (const path of paths) hash.update(path).update(await readFile(path));
const version = hash.digest("hex").slice(0, 16);
const assets = paths.map((path) =>
  relative("dist", path).replaceAll("\\", "/"),
);
const source = `// Generated by the build. Caches only this application's static assets.
const PREFIX = 'eso-scrying:' + self.registration.scope + ':';
const CACHE = PREFIX + '${version}';
const ASSETS = ${JSON.stringify(assets)};
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  await cache.addAll(ASSETS.map(path => new URL(path, self.registration.scope).href));
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  await Promise.all((await caches.keys()).filter(key => key.startsWith(PREFIX) && key !== CACHE).map(key => caches.delete(key)));
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (event.request.mode === 'navigate') {
      try { const response = await fetch(event.request, {signal: AbortSignal.timeout(4000)}); if (response.ok) return response; } catch {}
      return (await cache.match(new URL('index.html', self.registration.scope))) || Response.error();
    }
    return (await cache.match(event.request)) || fetch(event.request);
  })());
});
`;
await writeFile("dist/sw.js", source);
console.log(
  `Offline cache: ${assets.length} local assets, version ${version}.`,
);
